import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

// Set PLAYWRIGHT_MODULE to an existing playwright/index.mjs if it is not local.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL||'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await mkdir('outputs',{recursive:true});
try {
 await page.goto('http://127.0.0.1:5173/',{waitUntil:'domcontentloaded'});
 await page.locator('[data-ready="true"]').waitFor();
 await page.getByRole('heading',{name:/Hello, dost/}).waitFor();
 await page.screenshot({path:'outputs/desktop.png',fullPage:true,animations:'disabled'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.getByRole('button',{name:'Add entry',exact:true}).click();
 await page.getByLabel('Amount (₹)').fill('850');
 await page.getByLabel('Description').fill('Delivery shift');
 await page.getByRole('button',{name:'Save entry'}).click();
 await page.getByRole('button',{name:'Add entry',exact:true}).click();
 await page.getByRole('combobox',{name:'Entry type',exact:true}).selectOption('expense');
 await page.getByLabel('Amount (₹)').fill('150');
 await page.getByLabel('Description').fill('Fuel');
 await page.getByRole('button',{name:'Save entry'}).click();
 assert.match(await page.locator('.big-money').textContent(),/700/);
 await page.getByRole('button',{name:'My earnings',exact:true}).click();
 assert.equal(await page.locator('tbody tr').count(),2);
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export',exact:true}).click();
 assert.equal((await downloadPromise).suggestedFilename(),'saathi-earnings.csv');
 await page.getByRole('button',{name:'My documents',exact:true}).click();
 await page.locator('input[type=checkbox]').first().check();
 assert.match(await page.locator('.progress-label').textContent(),/1 of 4/);
 await page.getByRole('button',{name:'Grievance help',exact:true}).click();
 await page.getByLabel('What happened?').fill('My payment of ₹850 for 12 deliveries on 14 October has not arrived.');
 await page.getByRole('button',{name:'Use an editable English template'}).click();
 assert.match(await page.locator('#draft-edit').inputValue(),/₹850/);
 await page.getByRole('button',{name:'Save draft',exact:true}).click();
 await page.getByRole('combobox',{name:'Status for Payment not received'}).selectOption('Sent');
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('[data-ready="true"]').waitFor();
 await page.getByRole('button',{name:'My earnings',exact:true}).click();
 assert.equal(await page.locator('tbody tr').count(),2);
 await page.getByRole('button',{name:'My documents',exact:true}).click();
 assert.equal(await page.locator('input[type=checkbox]').first().isChecked(),true);
 await page.getByRole('button',{name:'Grievance help',exact:true}).click();
 assert.equal(await page.getByRole('combobox',{name:'Status for Payment not received'}).inputValue(),'Sent');
 await page.locator('.language-button').click();
 assert.equal(await page.locator('.language-option').count(),23);
 await page.getByRole('button',{name:'हिन्दी Hindi'}).click();
 await page.getByRole('button',{name:'एक नज़र',exact:true}).click();
 await page.getByRole('heading',{name:/नमस्ते, दोस्त/}).waitFor();
 await page.locator('.language-button').click();
 await page.getByRole('button',{name:'English English'}).click();
 await page.getByRole('button',{name:'Ask Saathi AI',exact:true}).click();
 const config=await (await page.request.get('http://localhost:5173/api/assistant')).json();
 if(!config.configured){await page.getByRole('textbox',{name:'Ask Saathi',exact:true}).fill('How do I register for e-Shram?');await page.getByRole('button',{name:'Send message',exact:true}).click();await page.getByText('AI is not connected yet.',{exact:false}).first().waitFor();}
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await page.screenshot({path:'outputs/desktop-with-records.png',fullPage:true,animations:'disabled'});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'outputs/mobile.png',fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'Open navigation'}).click();
 await page.getByRole('button',{name:'Safety & wellbeing',exact:true}).click();
 assert.equal(await page.getByRole('link',{name:'Call 112',exact:true}).getAttribute('href'),'tel:112');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 console.log('Browser checks passed: income/expenses, CSV export, checklist persistence, draft save/status, 23 language choices, Hindi navigation, AI configuration feedback, mobile layout and emergency link.');
} catch(error) { console.error('Browser errors:',errors); await page.screenshot({path:'outputs/browser-failure.png',fullPage:true,animations:'disabled'}); throw error; } finally { await browser.close(); }
